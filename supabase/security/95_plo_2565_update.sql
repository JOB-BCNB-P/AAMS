-- ============================================================================
-- 95_plo_2565_update.sql — ปรับข้อความ PLO 1–10
-- หลักสูตรพยาบาลศาสตรบัณฑิต ฉบับปรับปรุง พ.ศ. 2565 (curriculum_plo.curriculum_year = '2565')
-- ----------------------------------------------------------------------------
-- แก้เฉพาะ "ข้อความ" ของ PLO หลัก (แถวที่ไม่มี parent_code)
--   • ไม่แตะรหัส PLO — CLO ที่ผูกไว้ แผนที่กระจาย PLO และ Sub-PLO จึงยังเชื่อมกันเหมือนเดิม
--   • จับคู่ด้วย "เลข PLO" (PLO1 / 1 / PLO 1 ถือว่าเป็นข้อเดียวกัน)
--   • ข้อไหนยังไม่มีในระบบ จะเพิ่มให้ โดยใช้รูปแบบรหัสเดียวกับ PLO ที่มีอยู่
--   • หลักสูตรฉบับอื่น (เช่น 2570) ไม่ถูกแตะ
-- วิธีใช้: Supabase → SQL Editor → วางทั้งไฟล์ → Run (รันซ้ำได้) ตารางท้ายไฟล์คือผลลัพธ์
-- ============================================================================
do $$
declare
  v_year   text := '2565';
  v_prefix text;
  r        record;
  v_hit    int;
begin
  -- รูปแบบรหัสที่ใช้อยู่ (เช่น "PLO1" หรือ "1")
  select case when bool_or(plo_code ~* '^\s*plo') then 'PLO' else '' end
    into v_prefix
    from public.curriculum_plo
   where curriculum_year = v_year and coalesce(btrim(parent_code), '') = '';
  v_prefix := coalesce(v_prefix, 'PLO');

  for r in
    select * from (values
      (1,  'ประยุกต์ความรู้ทางการพยาบาล การผดุงครรภ์และบูรณาการศาสตร์ที่เกี่ยวข้องในการให้บริการสุขภาพทุกช่วงวัย ในภาวะปกติและเจ็บป่วย'),
      (2,  'ปฏิบัติการพยาบาลและการผดุงครรภ์แบบองค์รวมด้วยหัวใจความเป็นมนุษย์โดยใช้กระบวนการพยาบาลบนหลักฐานเชิงประจักษ์คำนึงถึงความปลอดภัย การใช้ยาอย่างสมเหตุผล ความหลากหลายทางวัฒนธรรมภายใต้กฎหมายและจรรยาบรรณวิชาชีพ'),
      (3,  'แสดงออกถึงพฤติกรรมด้านคุณธรรม จริยธรรม จรรยาบรรณวิชาชีพ เจตคติที่ดีต่อวิชาชีพและปกป้องสิทธิของผู้รับบริการ'),
      (4,  'แสดงออกถึงทักษะการคิดขั้นสูง ในการตัดสินใจแก้ปัญหาการคิดอย่างมีวิจารณญาณและสร้างสรรค์'),
      (5,  'ประยุกต์ความรู้ระเบียบวิธีวิจัยในการปฏิบัติการพยาบาล การผดุงครรภ์และร่วมออกแบบหรือพัฒนานวัตกรรมการดูแลสุขภาพ'),
      (6,  'แสดงออกถึงการมีภาวะผู้นำ และสามารถบริหารจัดการสุขภาวะชุมชน'),
      (7,  'ใช้ภาษาในการสื่อสารได้อย่างเหมาะสมและเป็นสากล'),
      (8,  'ใช้สื่อสารสนเทศและเทคโนโลยีดิจิทัล ที่เหมาะสมในการเรียนรู้และปฏิบัติการพยาบาลและการผดุงครรภ์'),
      (9,  'แสดงออกถึงการมีทักษะชีวิต โดยยึดหลักปรัชญาเศรษฐกิจพอเพียงเพื่อพัฒนาตนเอง วิชาชีพ และสังคม'),
      (10, 'ประยุกต์แนวคิดการเป็นผู้ประกอบการด้านสุขภาพในการปฏิบัติงานได้อย่างเหมาะสม')
    ) as t(no, txt)
  loop
    update public.curriculum_plo
       set statement_th = r.txt
     where curriculum_year = v_year
       and coalesce(btrim(parent_code), '') = ''
       and regexp_replace(plo_code, '[^0-9.]', '', 'g') = r.no::text;
    get diagnostics v_hit = row_count;

    if v_hit = 0 then
      insert into public.curriculum_plo (curriculum_year, plo_code, statement_th, parent_code, sort_order)
      values (v_year, v_prefix || r.no, r.txt, '', r.no * 100);
      raise notice 'เพิ่ม PLO%  (ยังไม่มีในระบบ)', r.no;
    end if;
  end loop;
end $$;

-- ตรวจผล: PLO หลักของหลักสูตร 2565 ทั้งหมด
select plo_code, statement_th
  from public.curriculum_plo
 where curriculum_year = '2565' and coalesce(btrim(parent_code), '') = ''
 order by nullif(regexp_replace(plo_code, '[^0-9]', '', 'g'), '')::int nulls last, plo_code;
