--   ยกเว้นอัตโนมัติ : ผู้สำเร็จการศึกษา ผู้พ้นสภาพ และผู้ลาพักการศึกษา
--   ยกเว้นรายคน    : ผู้ดูแลกดปลดล็อกได้จากหน้าติดตามอัตราการตอบ
