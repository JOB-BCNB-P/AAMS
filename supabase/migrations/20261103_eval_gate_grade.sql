-- ───────── 1) รายชื่อที่ผู้ดูแลปลดล็อกให้เป็นรายคน ─────────
create table if not exists public.eval_grade_exempt (
  id          bigint generated by default as identity primary key,
  student_id  text not null unique,
  reason      text        default '',
  created_by  text        default '',
  created_at  timestamptz default now()
);
alter table public.eval_grade_exempt enable row level security;

drop policy if exists p_read  on public.eval_grade_exempt;
drop policy if exists p_write on public.eval_grade_exempt;

create policy p_read on public.eval_grade_exempt for select
  using (ems.has_any_role(array['admin','academic']) or student_id = ems.student_id());

create policy p_write on public.eval_grade_exempt for all
  using (ems.has_any_role(array['admin','academic']))
  with check (ems.has_any_role(array['admin','academic']));

comment on table public.eval_grade_exempt is
  'นักศึกษาที่ผู้ดูแลปลดล็อกให้ดูผลการเรียนได้ แม้ยังไม่ได้ทำแบบประเมินรายวิชา';

-- ───────── 2) ตัวตัดสินว่าเกรดแถวนี้ถูกกันไว้หรือยัง ─────────
create or replace function ems.grade_locked(
  p_student_id text, p_subject_code text, p_semester text, p_academic_year text
) returns boolean
language sql stable security definer
set search_path = public, ems
cost 1000                      -- ให้ตัววางแผนคิวรีเรียกทีหลังสุด จะได้ไม่ถ่วงแถวของเจ้าหน้าที่
as $$
  select exists (
    select 1
    from public.student s
    join public.eval_form f
      on  btrim(coalesce(f.subject_code, ''))  = btrim(coalesce(p_subject_code, ''))
      and btrim(coalesce(f.semester, ''))      = btrim(coalesce(p_semester, ''))
      and btrim(coalesce(f.academic_year, '')) = btrim(coalesce(p_academic_year, ''))
    where btrim(coalesce(s.student_id, '')) = btrim(coalesce(p_student_id, ''))

      -- ยกเว้น : ผู้สำเร็จการศึกษา ผู้พ้นสภาพ ผู้ลาพักการศึกษา
      and btrim(coalesce(s.status, ''))     = 'กำลังศึกษา'
      and btrim(coalesce(s.year_level, '')) <> 'จบ'

      -- ต้องเป็นแบบประเมินที่เปิดอยู่จริงในวันนี้ (เวลาไทย) เท่านั้น
      and btrim(coalesce(f.status, '')) = 'เปิด'
      and (btrim(coalesce(f.open_date, ''))  = '' or btrim(f.open_date)  <= to_char(now() at time zone 'Asia/Bangkok', 'YYYY-MM-DD'))
      and (btrim(coalesce(f.close_date, '')) = '' or btrim(f.close_date) >= to_char(now() at time zone 'Asia/Bangkok', 'YYYY-MM-DD'))

      -- ต้องเป็นแบบประเมินที่ถึงมือนักศึกษาคนนี้จริง ตามรุ่น หรือชั้นปีถ้าไม่ได้ระบุรุ่น
      -- ถ้าไม่ตรวจข้อนี้ คนที่ระบบไม่ได้ให้ประเมินจะถูกล็อกโดยไม่มีทางปลดล็อกด้วยตัวเอง
      and case when btrim(coalesce(f.batch, '')) <> ''
               then btrim(coalesce(f.batch, '')) = btrim(coalesce(s.batch, ''))
               else btrim(coalesce(f.year_level, '')) <> ''
                and btrim(coalesce(f.year_level, '')) = btrim(coalesce(s.year_level, ''))
          end

      -- ผู้ดูแลปลดล็อกให้แล้ว
      and not exists (
        select 1 from public.eval_grade_exempt e
        where btrim(coalesce(e.student_id, '')) = btrim(coalesce(p_student_id, ''))
      )

      -- ส่งแบบประเมินแล้ว (บันทึกร่างค้างไว้ยังไม่นับ)
      and not exists (
        select 1 from public.eval_response r
        where btrim(coalesce(r.form_code, ''))  = btrim(coalesce(f.form_code, ''))
          and btrim(coalesce(r.student_id, '')) = btrim(coalesce(p_student_id, ''))
          and btrim(coalesce(r.status, ''))     = 'ส่งแล้ว'
      )
  );
$$;

comment on function ems.grade_locked(text, text, text, text) is
  'true = เกรดแถวนี้ยังถูกกันไว้ เพราะเจ้าของยังไม่ส่งแบบประเมินของรายวิชาที่เปิดให้ประเมินอยู่';

revoke all on function ems.grade_locked(text, text, text, text) from public;
grant execute on function ems.grade_locked(text, text, text, text) to authenticated;

-- ───────── 3) นโยบายอ่านตาราง grade ─────────
-- เหมือนเดิมทุกข้อ เพิ่มเงื่อนไขเฉพาะกิ่งของ "นักศึกษาเจ้าของเกรด" เท่านั้น
drop policy if exists p_read on public.grade;

create policy p_read on public.grade for select using (
  ems.sees_all_students()

  -- นักศึกษาเจ้าของเกรด : เห็นได้ถ้าไม่ติดประตูประเมินรายวิชา
  or (
    student_id = ems.student_id()
    and not ems.grade_locked(student_id, subject_code, semester, academic_year)
  )

  -- อาจารย์ผู้สอนรายวิชานั้น
  or (ems.has_role('teacher') and subject_code = any (ems.my_subject_codes()))

  -- อาจารย์ที่ปรึกษา
  or (
    ems.has_role('teacher') and ems.user_name() <> ''
    and exists (
      select 1 from public.student s
      where s.student_id = grade.student_id
        and lower(btrim(s.advisor)) = lower(btrim(ems.user_name()))
    )
  )

  -- อาจารย์ประจำชั้น
  or (
    ems.has_role('classTeacher') and ems.my_year() <> ''
    and exists (
      select 1 from public.student s
      where s.student_id = grade.student_id
        and btrim(coalesce(s.year_level, '')) = ems.my_year()
    )
  )
);

